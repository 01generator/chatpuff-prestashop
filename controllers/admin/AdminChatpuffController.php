/**
 * The ChatPuff entry of the back-office menu, the parent of Inbox and Settings: it opens the
 * inbox. Links from before 0.8.0 land here too.
 *
 * @property Chatpuff $module
 */
class AdminChatpuffController extends ModuleAdminController
{
    public function __construct()
    {
        $this->bootstrap = true;
        parent::__construct();
    }

    public function initContent(): void
    {
        Tools::redirectAdmin($this->context->link->getAdminLink('AdminChatpuffInbox'));
    }
}
